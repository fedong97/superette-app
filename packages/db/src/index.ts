export function createServices(db: Db, clock: Clock = () => new Date(), machineId?: () => string): Services {
  const admin = new AdminService(db, clock);
  const catalogue = new CatalogueService(db, clock);
  const stock = new StockService(db, clock);
  const inventories = new InventoryService(db, clock, stock);
  const transfers = new TransferService(db, clock, stock);
  const monitoring = new MonitoringService(db, clock, stock);
  const production = new ProductionService(db, clock, stock);
  const customers = new CustomerService(db, clock);
  const expenses = new ExpenseService(db, clock);
  const charges = new ChargeService(db, clock);
  const controls = new ControlService(db, clock, customers);
  const quotes = new QuoteService(db, clock, admin, catalogue);
  const orders = new OrderService(db, clock, admin, catalogue);
  const commissions = new CommissionService(db, clock);
  const promotions = new PromotionService(db, clock, catalogue);
  const backups = new BackupService(db, clock);
  const labels = new LabelService(db, clock, catalogue, promotions);
  const treasury = new TreasuryService(db, clock);
  const emoney = new EmoneyService(db, clock);
  const rebates = new RebateService(db, clock, treasury);
  const deliveries = new DeliveryService(db, clock);
  const loyalty = new LoyaltyService(db, clock, admin);
  const mobilePay = new MobilePayService(db, clock);
  const pos = new PosService(db, clock, admin, catalogue, stock, customers, quotes, promotions, treasury, emoney, deliveries, loyalty, orders);
  const purchases = new PurchaseService(db, clock, stock);
  const receipts = new ReceiptService(db, clock, admin, pos, customers, expenses, treasury, inventories, rebates, quotes, purchases);
  const staff = new StaffService(db, clock, admin);
  const cashdesk = new CashDeskService(db, clock, pos, customers, purchases, expenses, staff, treasury);
  const reports = new ReportService(db, clock);
  const accounting = new AccountingService(db, clock);
  const statements = new FinancialStatementsService(db, clock, accounting, stock);
  const fiscal = new FiscalYearService(db, clock, accounting, statements);
  const reconciliation = new ReconciliationService(db, clock, accounting);
  const tax = new TaxService(db, clock, accounting, statements);
  const disclosures = new DisclosureService(db, clock);
  const notes = new NotesService(db, clock, accounting, statements, tax, disclosures);
  const attention = new AttentionService(db, clock, stock, pos, purchases, customers, rebates);
  const digest = new DigestService(db, clock, admin, reports, attention);
  const sync = new SyncService(db, clock, stock);
  const license = new LicenseService(db, clock, () => sync.credentials() !== null, machineId);
  const fiches = new FicheService(db, clock, sync);
  const repair = new RepairService(db, clock, backups);
  const relay = new RelayService(db, clock, sync);
  const templates = new TemplateService(db, clock, admin, catalogue);
  const opening = new OpeningService(db, clock, catalogue, customers, purchases, stock);
  const assets = new AssetService(db, clock);
  const staffTime = new StaffTimeService(db, clock, admin);
  const attendance = new AttendanceService(db, clock, admin, staffTime);
  const containers = new ContainerService(db, clock, pos, cashdesk);
  const agent = new AgentService(db, clock, pos, cashdesk);
  const cashierControl = new CashierControlService(db, clock);
  const clearance = new ClearanceService(db, clock, admin, catalogue, promotions);
  const cycleCount = new CycleCountService(db, clock, admin, inventories);
  const couriers = new CourierService(db, clock, deliveries, customers, pos);
  const supplierReturns = new SupplierReturnService(db, clock, stock, purchases);
  const summaryInvoices = new SummaryInvoiceService(db, clock);
  const cheques = new ChequeService(db, clock);
  const planning = new PlanningService(db, clock, accounting, customers, purchases, charges, reports);
  return { db, containers, agent, staffTime, cashierControl, clearance, cycleCount, couriers, attendance, supplierReturns, summaryInvoices, cheques, planning, opening, assets, fiches, repair, relay, templates, admin, catalogue, stock, inventories, transfers, monitoring, production, customers, loyalty, mobilePay, expenses, charges, controls, quotes, orders, commissions, pos, deliveries, treasury, emoney, staff, cashdesk, rebates, promotions, labels, backups, receipts, purchases, reports, accounting, statements, fiscal, reconciliation, tax, notes, disclosures, attention, digest, sync, license };
}

export function openServices(file: string, clock?: Clock): Services {
  return createServices(openDatabase(file), clock);
}
